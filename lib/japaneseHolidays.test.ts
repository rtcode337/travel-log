import { test } from "node:test";
import assert from "node:assert/strict";
import { isJapaneseHoliday, japaneseHolidayList } from "@/lib/japaneseHolidays";

// 内閣府が公表した各年の「国民の祝日」(振替休日・国民の休日を含む)と突き合わせる
const KNOWN: Record<number, string[]> = {
  // 2007年の改正前(振替休日は翌日だけ。1/1が日曜で1/2が振替)
  2006: ["01-01", "01-02", "01-09", "02-11", "03-21", "04-29", "05-03", "05-04", "05-05",
    "07-17", "09-18", "09-23", "10-09", "11-03", "11-23", "12-23"],
  // 5/3が日曜で5/6が振替、敬老の日と秋分の日に挟まれた9/22が国民の休日
  2009: ["01-01", "01-12", "02-11", "03-20", "04-29", "05-03", "05-04", "05-05", "05-06",
    "07-20", "09-21", "09-22", "09-23", "10-12", "11-03", "11-23", "12-23"],
  // 即位の日と、それに挟まれた4/30・5/2の国民の休日。天皇誕生日は無い
  2019: ["01-01", "01-14", "02-11", "03-21", "04-29", "04-30", "05-01", "05-02", "05-03",
    "05-04", "05-05", "05-06", "07-15", "08-11", "08-12", "09-16", "09-23", "10-14",
    "10-22", "11-03", "11-04", "11-23"],
  // 東京五輪で海の日・スポーツの日・山の日が移動
  2020: ["01-01", "01-13", "02-11", "02-23", "02-24", "03-20", "04-29", "05-03", "05-04",
    "05-05", "05-06", "07-23", "07-24", "08-10", "09-21", "09-22", "11-03", "11-23"],
  2021: ["01-01", "01-11", "02-11", "02-23", "03-20", "04-29", "05-03", "05-04", "05-05",
    "07-22", "07-23", "08-08", "08-09", "09-20", "09-23", "11-03", "11-23"],
  2025: ["01-01", "01-13", "02-11", "02-23", "02-24", "03-20", "04-29", "05-03", "05-04",
    "05-05", "05-06", "07-21", "08-11", "09-15", "09-23", "10-13", "11-03", "11-23", "11-24"],
  2026: ["01-01", "01-12", "02-11", "02-23", "03-20", "04-29", "05-03", "05-04", "05-05",
    "05-06", "07-20", "08-11", "09-21", "09-22", "09-23", "10-12", "11-03", "11-23"],
};

for (const [year, expected] of Object.entries(KNOWN)) {
  test(`${year}年の祝日の一覧`, () => {
    assert.deepEqual(japaneseHolidayList(Number(year)), expected);
  });
}

test("1日ずつの判定", () => {
  assert.equal(isJapaneseHoliday(2026, 9, 22), true); // 国民の休日
  assert.equal(isJapaneseHoliday(2026, 10, 12), true); // スポーツの日
  assert.equal(isJapaneseHoliday(2026, 10, 13), false);
});

test("対応する年の範囲外は分からない(null)", () => {
  assert.equal(isJapaneseHoliday(1999, 1, 1), null);
  assert.equal(isJapaneseHoliday(2100, 1, 1), null);
});
