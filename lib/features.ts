/**
 * 環境変数で畳める機能のフラグ。**どれも未設定なら有効**(Docker運用の従来どおりの
 * 挙動)で、載せる先の都合で成立しない機能をホスト側の設定だけで消せるようにするもの。
 *
 * `NEXT_PUBLIC_`を付けてあるのは、同じ判定をサーバーとブラウザの両方で使うため
 * (秘密ではなく「機能が有るか」を表すフラグ)。`fs`を読むモジュール
 * (`exportStorage.ts`・`photoStorage.ts`)とは別ファイルにしてあるのは、
 * クライアントコンポーネントから読めるようにするため。
 *
 * **APIと画面の両方を必ず塞ぐこと。** 画面だけ隠しても、APIが素通しなら
 * 直接叩けば動いてしまう(容量やコストを抑えるための設定なので意味が無くなる)。
 */

/**
 * 訪問記録のZIPエクスポート。生成はレスポンスを返したあとも走り続ける
 * バックグラウンド処理で、成果物はローカルFSに置く(`lib/exportStorage.ts`)。
 * **どちらもサーバーレスでは成立しない** —— レスポンスと同時にプロセスが終わり、
 * 書いたファイルも次の呼び出しには残らない。
 */
export const exportsEnabled =
  process.env.NEXT_PUBLIC_EXPORTS_ENABLED !== "false";

export const EXPORTS_DISABLED_MESSAGE =
  "この環境では訪問記録のエクスポートを利用できません(生成に永続ディスクと常駐プロセスが必要なため)。";

/**
 * 訪問記録への写真の添付。**保存先の容量が限られるホスト向けに畳めるようにしてある**
 * (Supabaseの無料プランはストレージ1GB)。畳むと入力欄が出なくなり、APIも
 * 写真つきの作成・更新を拒む。
 *
 * **既に保存されている写真の閲覧は止めない**(`/api/photos/...`はそのまま)。
 * 畳んだ理由は「これ以上増やさない」であって、記録済みのものを見せない理由は無い。
 */
export const photosEnabled =
  process.env.NEXT_PUBLIC_PHOTOS_ENABLED !== "false";

export const PHOTOS_DISABLED_MESSAGE =
  "この環境では訪問記録への写真の添付を利用できません。";
